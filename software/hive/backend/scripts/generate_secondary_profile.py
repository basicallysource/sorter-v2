NOT_EXPRESSIBLE = [
    "Rarity (sets a part appears in): no engine field, baked as a `part_num in [...]` list.",
    "Print relation: Rebrickable's parent/child print relationships are not in the dump and the engine has "
    "no decorated flag; part-number and name patterns approximate it.",
    "Per-part colour availability: the engine claims every listed colour for every matching part, so colour "
    "rules produce a parts x colours cross product; scoping the part list keeps the artifact small.",
    "Per-colour prices: the engine sees one representative price row per BrickLink item, not per colour.",
    "Negation (`not in`): the rare list is materialised instead of excluding common parts.",
]


def render_summary(
    rules: list[dict[str, Any]],
    catalog: Catalog,
    stats: dict[str, RuleStats],
    rest: RuleStats,
    *,
    rare_max_sets: int,
    price_min: float,
) -> str:
    pile = catalog.pile_pieces or 1
    lines = [
        f"# {PROFILE_NAME}: secondary profile summary",
        "",
        f"Generated {date.today().isoformat()} from `{catalog.csv_dir}`: {len(catalog.parts):,} parts, "
        f"{len(catalog.colors)} colours, {catalog.set_total:,} sets with a version-1 inventory, "
        f"{catalog.pile_pieces:,} inventory pieces. Parameters: rare-max-sets={rare_max_sets}, "
        f"price-min={price_min:g}.",
        "",
        "Rules in bin-priority order; the first matching rule claims a part (or a part/colour pair for "
        "colour rules). Counts are from the CSVs, so they say nothing about BrickLink-only fields.",
        "",
        "| # | Rule | Expression | Parts matching | Parts claimed | Colour keys | Inventory pairs | Pile share |",
        "|---|------|------------|---------------:|--------------:|------------:|----------------:|-----------:|",
    ]
    for idx, rule in enumerate(rules, start=1):
        s = stats[rule["id"]]
        if _csv_evaluable(rule):
            counts = (f"{s.parts_gross:,} | {s.parts_claimed:,} | {s.color_keys:,} | {s.inventory_pairs:,} | "
                      f"{100 * s.pile_pieces / pile:.1f}%")
        else:
            counts = "n/a | n/a | n/a | n/a | n/a"
        lines.append(f"| {idx} | {rule['name']} (`{rule['id']}`) | {_describe_rule(rule, catalog)} | {counts} |")
    lines.append(
        f"| | Pass-through (`{DEFAULT_CATEGORY_ID}`) | no rule matched | | | | "
        f"{rest.inventory_pairs:,} | {100 * rest.pile_pieces / pile:.1f}% |"
    )
    lines += ["", "## Rule notes", ""]
    for rule in rules:
        lines.append(f"- **{rule['name']}** (`{rule['id']}`): {RULE_NOTES[rule['id']]}")
    lines += ["", "## Not expressible in the rule engine", ""]
    lines += [f"- {item}" for item in NOT_EXPRESSIBLE]
    lines += [
        "",
        "## Import",
        "",
        "`POST /api/profiles` to create the profile, then `POST /api/profiles/{id}/versions` with the "
        "generated JSON as the body (cookie session plus `X-CSRF-Token`). `POST /api/profiles/preview` "
        "dry-runs the same document.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("csv_dir", type=Path, help="directory with the Rebrickable CSVs")
    parser.add_argument("--out", type=Path, default=Path("seltenes-und-besonderes.json"),
                        help="profile JSON (default: %(default)s)")
    parser.add_argument("--summary", type=Path, default=None,
                        help="markdown summary (default: <out>.md)")
    parser.add_argument("--name", default=PROFILE_NAME, help="profile name (default: %(default)s)")
    parser.add_argument("--rare-max-sets", type=int, default=20,
                        help="a part is rare below this many sets (default: %(default)s)")
    parser.add_argument("--price-min", type=float, default=2.0,
                        help="bl_price_avg threshold for the high-value rule (default: %(default)s)")
    parser.add_argument("--no-publish", action="store_true", help="emit publish: false")
    args = parser.parse_args(argv)
    summary_path = args.summary or args.out.with_suffix(".md")

    catalog = load_catalog(args.csv_dir)
    rules = build_rules(catalog, rare_max_sets=args.rare_max_sets, price_min=args.price_min)
    stats, rest = collect_stats(rules, catalog)

    payload = build_payload(rules, name=args.name, publish=not args.no_publish)
    args.out.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    summary_path.write_text(
        render_summary(rules, catalog, stats, rest, rare_max_sets=args.rare_max_sets, price_min=args.price_min),
        encoding="utf-8",
    )
    print(f"wrote {args.out} ({len(rules)} rules) and {summary_path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
