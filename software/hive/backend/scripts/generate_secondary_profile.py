#!/usr/bin/env python3
"""Generate the "Seltenes und Besonderes" secondary sorting profile.

Reads a Rebrickable CSV dump (colors, part_categories, parts, sets,
inventories, inventory_parts) and writes

- the profile JSON in the shape of ``POST /api/profiles/{id}/versions``
  (``SortingProfileVersionCreateRequest``): one filter rule per target
  category, every rule tagged ``role: "secondary"``, in bin-priority order;
- a markdown summary with what each rule matches in the CSVs and what the
  rule engine cannot express.

The CSVs stay where they are; pass their directory:

    uv run scripts/generate_secondary_profile.py /tmp/rb \\
        --out /tmp/seltenes-und-besonderes.json

Rarity is not a rule-engine field, so the rare rule is baked as a
``part_num in [...]`` list from the inventories. Regenerate after a CSV
refresh to keep it current.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from collections import Counter
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Any

csv.field_size_limit(10**9)

PROFILE_NAME = "Seltenes und Besonderes"
PROFILE_DESCRIPTION = (
    "Secondary profile: side-sorts printed, minifig, transparent, metallic, "
    "wheel, special Technic and rare parts. Generated by "
    "scripts/generate_secondary_profile.py from the Rebrickable CSVs."
)
DEFAULT_CATEGORY_ID = "misc"

# Rebrickable part_categories ids.
CAT_MINIFIG_HEADS = [59, 62]
CAT_MINIFIG_TORSOS = [60, 63]
CAT_MINIFIG_LEGS = [61, 64]
CAT_MINIFIG_ACCESSORIES = [27, 65, 70, 71, 72, 73, 13]
CAT_ANIMALS_PLANTS = [28, 74, 75, 76]
CAT_WINDOWS_DOORS_PANELS = [16, 23, 47]
CAT_WHEELS_TYRES = [29]
CAT_TECHNIC_SPECIAL = [52, 17, 22, 25, 44, 45, 26]
# Never pieces in a pile: sticker sheets, Duplo, non-System, pens and watches.
CAT_NOT_A_PIECE = [58, 4, 77, 78]

PRINTED_PART_NUM_RE = r"(?:pr|pb|pat)\d"
PRINTED_NAME_RE = r"\bprint(?:ed)?\b"
TECHNIC_SPECIAL_NAME_RE = r"differential|shock absorber|motor"
METALLIC_COLOR_RE = r"chrome|metal|pearl|speckle|copper|silver|gold|two-tone"


@dataclass(frozen=True)
class Part:
    part_num: str
    name: str
    cat_id: int


@dataclass
class Catalog:
    csv_dir: Path
    parts: dict[str, Part]
    categories: dict[int, str]
    colors: dict[int, tuple[str, bool]]  # id -> (name, is_trans)
    set_count: Counter[str] = field(default_factory=Counter)  # part_num -> distinct sets
    part_colors: dict[str, set[int]] = field(default_factory=dict)
    pair_qty: Counter[tuple[str, int]] = field(default_factory=Counter)  # pieces over all inventories
    set_total: int = 0

    @property
    def pile_pieces(self) -> int:
        return sum(self.pair_qty.values())


def load_catalog(csv_dir: Path) -> Catalog:
    with open(csv_dir / "part_categories.csv", newline="", encoding="utf-8") as fh:
        categories = {int(r["id"]): r["name"] for r in csv.DictReader(fh)}
    with open(csv_dir / "colors.csv", newline="", encoding="utf-8") as fh:
        colors = {int(r["id"]): (r["name"], r["is_trans"] == "True") for r in csv.DictReader(fh)}
    with open(csv_dir / "parts.csv", newline="", encoding="utf-8") as fh:
        parts = {
            r["part_num"]: Part(r["part_num"], r["name"], int(r["part_cat_id"]))
            for r in csv.DictReader(fh)
        }
    catalog = Catalog(csv_dir, parts, categories, colors)

    # One inventory per set: version 1 only, like the analysis scripts.
    with open(csv_dir / "inventories.csv", newline="", encoding="utf-8") as fh:
        inv_set = {r["id"]: r["set_num"] for r in csv.DictReader(fh) if r["version"] == "1"}
    catalog.set_total = len(set(inv_set.values()))

    part_sets: dict[str, set[str]] = {}
    with open(csv_dir / "inventory_parts.csv", newline="", encoding="utf-8") as fh:
        reader = csv.reader(fh)
        header = next(reader)
        col = {name: idx for idx, name in enumerate(header)}
        i_inv, i_part, i_color, i_qty, i_spare = (
            col["inventory_id"], col["part_num"], col["color_id"], col["quantity"], col["is_spare"],
        )
        for row in reader:
            set_num = inv_set.get(row[i_inv])
            if set_num is None or row[i_spare] == "True":
                continue
            part_num = row[i_part]
            color_id = int(row[i_color])
            part_sets.setdefault(part_num, set()).add(set_num)
            catalog.part_colors.setdefault(part_num, set()).add(color_id)
            catalog.pair_qty[(part_num, color_id)] += int(row[i_qty])
    catalog.set_count = Counter({p: len(s) for p, s in part_sets.items()})
    return catalog


# --- rule construction -------------------------------------------------------

def _cond(rule_id: str, n: int, field_name: str, op: str, value: Any) -> dict[str, Any]:
    return {"id": f"{rule_id}-c{n}", "field": field_name, "op": op, "value": value}


def _rule(
    rule_id: str,
    name: str,
    conditions: list[dict[str, Any]],
    *,
    match_mode: str = "all",
    children: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    return {
        "id": rule_id,
        "rule_type": "filter",
        "role": "secondary",
        "name": name,
        "match_mode": match_mode,
        "conditions": conditions,
        "children": children or [],
        "disabled": False,
    }


def _category_rule(rule_id: str, name: str, cat_ids: list[int]) -> dict[str, Any]:
    return _rule(rule_id, name, [_cond(rule_id, 1, "category_id", "in", cat_ids)])


def _color_rule(rule_id: str, name: str, catalog: Catalog, color_ids: list[int]) -> dict[str, Any]:
    # The engine claims every listed colour for every matching part, so an
    # unscoped colour rule would emit parts x colours keys for the whole
    # catalogue. Scope it to parts that ship in one of these colours.
    wanted = set(color_ids)
    part_nums = sorted(p for p, cols in catalog.part_colors.items() if cols & wanted and p in catalog.parts)
    return _rule(rule_id, name, [
        _cond(rule_id, 1, "part_num", "in", part_nums),
        _cond(rule_id, 2, "color_id", "in", color_ids),
    ])


def build_rules(catalog: Catalog, *, rare_max_sets: int, price_min: float) -> list[dict[str, Any]]:
    trans_colors = sorted(cid for cid, (_, is_trans) in catalog.colors.items() if is_trans)
    metallic_colors = sorted(
        cid for cid, (name, is_trans) in catalog.colors.items()
        if not is_trans and re.search(METALLIC_COLOR_RE, name, re.IGNORECASE)
    )
    rules = [
        _rule("printed", "Printed parts", [
            _cond("printed", 1, "part_num", "regex", PRINTED_PART_NUM_RE),
            _cond("printed", 2, "name", "regex", PRINTED_NAME_RE),
        ], match_mode="any"),
        _category_rule("minifig-heads", "Minifig heads", CAT_MINIFIG_HEADS),
        _category_rule("minifig-torsos", "Minifig torsos", CAT_MINIFIG_TORSOS),
        _category_rule("minifig-legs", "Minifig legs", CAT_MINIFIG_LEGS),
        _category_rule("minifig-accessories", "Minifig accessories and headgear", CAT_MINIFIG_ACCESSORIES),
        _category_rule("animals-plants", "Animals and plants", CAT_ANIMALS_PLANTS),
        _category_rule("windows-doors-panels", "Windows, doors and panels", CAT_WINDOWS_DOORS_PANELS),
        _color_rule("transparent", "Transparent parts", catalog, trans_colors),
        _color_rule("metallic", "Chrome, metallic and pearl parts", catalog, metallic_colors),
        _category_rule("wheels-tyres", "Wheels and tyres", CAT_WHEELS_TYRES),
        _rule("technic-special", "Technic special (gears, pneumatics, motors, differentials, shocks)", [
            _cond("technic-special", 1, "category_id", "in", CAT_TECHNIC_SPECIAL),
        ], match_mode="any", children=[
            _rule("technic-special-by-name", "Technic part named like a special", [
                _cond("technic-special-by-name", 1, "category_name", "contains", "Technic"),
                _cond("technic-special-by-name", 2, "name", "regex", TECHNIC_SPECIAL_NAME_RE),
            ]),
        ]),
    ]
    claims = simulate(rules, catalog)
    rare = sorted(
        p for p, part in catalog.parts.items()
        if 1 <= catalog.set_count.get(p, 0) < rare_max_sets
        and part.cat_id not in CAT_NOT_A_PIECE
        and (p, None) not in claims
    )
    rules.append(_rule("rare", f"Rare parts (in fewer than {rare_max_sets} sets)", [
        _cond("rare", 1, "part_num", "in", rare),
    ]))
    rules.append(_rule("high-value", f"High-value parts (BrickLink used avg >= {price_min:g})", [
        _cond("high-value", 1, "bl_price_avg", "gte", price_min),
    ]))
    return rules


# --- CSV-side mirror of the rule engine ---------------------------------------
# Same operators and first-claim semantics as
# app/services/profile_engine/rule_engine.generateProfile, restricted to the
# fields the CSVs carry; anything else evaluates to None (never matches).

CSV_FIELDS = frozenset({"category_id", "category_name", "name", "part_num", "color_id"})


def _csv_evaluable(rule: dict[str, Any]) -> bool:
    return all(c["field"] in CSV_FIELDS for c in rule["conditions"]) and all(
        _csv_evaluable(child) for child in rule["children"]
    )


def _field_value(field_name: str, part: Part, catalog: Catalog) -> Any:
    if field_name == "category_id":
        return part.cat_id
    if field_name == "category_name":
        return catalog.categories.get(part.cat_id, "")
    if field_name == "name":
        return part.name
    if field_name == "part_num":
        return part.part_num
    return None


def _predicate(cond: dict[str, Any], part: Part, catalog: Catalog) -> bool:
    actual = _field_value(cond["field"], part, catalog)
    op, value = cond["op"], cond["value"]
    if op == "eq":
        return actual == value
    if op == "neq":
        return actual != value
    if op == "in":
        return actual in value
    if op == "contains":
        return isinstance(actual, str) and value.lower() in actual.lower()
    if op == "regex":
        return isinstance(actual, str) and bool(re.search(value, actual, re.IGNORECASE))
    if op == "gte":
        return actual is not None and actual >= value
    if op == "lte":
        return actual is not None and actual <= value
    return False


def _part_matches(rule: dict[str, Any], part: Part, catalog: Catalog) -> bool:
    results = [
        _predicate(c, part, catalog) for c in rule["conditions"] if c["field"] != "color_id"
    ]
    results += [
        _part_matches(child, part, catalog) for child in rule["children"] if not child.get("disabled")
    ]
    if not results:
        return True
    return (all if rule["match_mode"] == "all" else any)(results)


def _rule_colors(rule: dict[str, Any]) -> set[int] | None:
    colors: set[int] = set()
    found = False
    for c in rule["conditions"]:
        if c["field"] != "color_id":
            continue
        found = True
        if c["op"] == "eq":
            colors.add(c["value"])
        elif c["op"] == "in":
            colors.update(c["value"])
    for child in rule["children"]:
        child_colors = _rule_colors(child)
        if child_colors is not None:
            found = True
            colors |= child_colors
    return colors if found else None


def simulate(rules: list[dict[str, Any]], catalog: Catalog) -> dict[tuple[str, int | None], str]:
    """First-claim pass over the catalogue: (part_num, color_id|None) -> rule id."""
    claims: dict[tuple[str, int | None], str] = {}
    compiled = [(r, _rule_colors(r)) for r in rules if not r.get("disabled")]
    for part_num, part in catalog.parts.items():
        for rule, colors in compiled:
            if not _part_matches(rule, part, catalog):
                continue
            if colors is None:
                claims.setdefault((part_num, None), rule["id"])
                break
            for cid in colors:
                claims.setdefault((part_num, cid), rule["id"])
    return claims


@dataclass
class RuleStats:
    parts_gross: int = 0
    parts_claimed: int = 0
    color_keys: int = 0
    inventory_pairs: int = 0
    pile_pieces: int = 0


def collect_stats(rules: list[dict[str, Any]], catalog: Catalog) -> tuple[dict[str, RuleStats], RuleStats]:
    claims = simulate(rules, catalog)
    stats = {r["id"]: RuleStats() for r in rules}
    for rule in rules:
        stats[rule["id"]].parts_gross = sum(1 for p in catalog.parts.values() if _part_matches(rule, p, catalog))
    for (part_num, color_id), rule_id in claims.items():
        if color_id is None:
            stats[rule_id].parts_claimed += 1
        else:
            stats[rule_id].color_keys += 1
    rest = RuleStats()
    for (part_num, color_id), qty in catalog.pair_qty.items():
        rule_id = claims.get((part_num, color_id)) or claims.get((part_num, None))
        target = stats[rule_id] if rule_id else rest
        target.inventory_pairs += 1
        target.pile_pieces += qty
    return stats, rest


# --- output ------------------------------------------------------------------

def build_payload(rules: list[dict[str, Any]], *, name: str, publish: bool) -> dict[str, Any]:
    return {
        "name": name,
        "description": PROFILE_DESCRIPTION,
        "default_category_id": DEFAULT_CATEGORY_ID,
        "rules": rules,
        "fallback_mode": {"rebrickable_categories": False, "bricklink_categories": False, "by_color": False},
        "change_note": f"generated by scripts/generate_secondary_profile.py on {date.today().isoformat()}",
        "label": None,
        "publish": publish,
    }


def _describe_condition(cond: dict[str, Any], catalog: Catalog) -> str:
    value = cond["value"]
    if cond["op"] == "in":
        if cond["field"] == "category_id":
            value = ", ".join(catalog.categories.get(v, str(v)) for v in value)
        elif cond["field"] == "color_id":
            value = f"{len(value)} colours"
        else:
            value = f"{len(value):,} {cond['field']}s"
        return f"{cond['field']} in [{value}]"
    if cond["op"] == "regex":
        return f"{cond['field']} ~ `{value}`"
    return f"{cond['field']} {cond['op']} {value!r}"


def _describe_rule(rule: dict[str, Any], catalog: Catalog) -> str:
    joiner = " AND " if rule["match_mode"] == "all" else " OR "
    parts = [_describe_condition(c, catalog) for c in rule["conditions"]]
    parts += [f"({_describe_rule(child, catalog)})" for child in rule["children"]]
    return joiner.join(parts)


